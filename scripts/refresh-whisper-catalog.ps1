$ErrorActionPreference = 'Stop'
# Refresh only supported Whisper formats; review the generated hashes before publishing.
$catalog = Invoke-RestMethod 'https://huggingface.co/api/models/ggerganov/whisper.cpp?blobs=true'
if ($catalog.sha -notmatch '^[a-f0-9]{40}$') { throw 'Invalid Hugging Face revision' }
$entries = @($catalog.siblings | Where-Object {
    $_.rfilename -match '^ggml-((tiny|base|small|medium)(\.en)?|large-v[123]|large-v3-turbo)(-q[58]_[01])?\.bin$'
} | Sort-Object rfilename)
if ($entries.Count -lt 20) { throw 'Incomplete Whisper catalog' }
$lines = @('// Generated by scripts/refresh-whisper-catalog.ps1 from Hugging Face LFS metadata.', 'use super::Artifact;', '', 'pub(super) static MODELS: &[(&str, Artifact)] = &[')
foreach ($item in $entries) {
    if ($item.lfs.sha256 -notmatch '^[a-f0-9]{64}$' -or $item.size -ne $item.lfs.size -or $item.size -le 0) { throw 'Invalid artifact metadata' }
    $id = $item.rfilename -replace '^ggml-', '' -replace '\.bin$', ''
    $lines += '    ("' + $id + '", Artifact {'
    $lines += '        name: "model",'
    $lines += '        file: "' + $item.rfilename + '",'
    $lines += '        url: "https://huggingface.co/ggerganov/whisper.cpp/resolve/' + $catalog.sha + '/' + $item.rfilename + '",'
    $lines += '        sha256: "' + $item.lfs.sha256 + '",'
    $lines += '        size: ' + $item.size + ','
    $lines += '    }),'
}
$lines += '];'
$target = Join-Path $PSScriptRoot '../src-tauri/src/stt/stt_models.rs'
[System.IO.File]::WriteAllText($target, ($lines -join "`n") + "`n")
Write-Output ('Pinned ' + $entries.Count + ' Whisper artifacts. Run cargo fmt before reviewing the diff.')
